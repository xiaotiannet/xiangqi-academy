/* ---------- 随机取词（避免连续重复） ---------- */

const lastIdx = new Map<string, number>();

export function pick(key: string, pool: Line[]): Line {
  if (pool.length === 0) return L('');
  const prev = lastIdx.get(key) ?? -1;
  let i = Math.floor(Math.random() * pool.length);
  if (pool.length > 1 && i === prev) i = (i + 1 + Math.floor(Math.random() * (pool.length - 1))) % pool.length;
  lastIdx.set(key, i);
  return pool[i];
}

export function greetPool(hour = new Date().getHours()): Line[] {
  if (hour < 5) return GREET.night;
  if (hour < 11) return GREET.morning;
  if (hour < 18) return GREET.afternoon;
  if (hour < 23) return GREET.evening;
  return GREET.night;
}

export function fill(line: Line, vars: Record<string, string | number>): Line {
  const sub = (s: string) => s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return { t: sub(line.t), v: sub(line.v ?? line.t) };
}

export function template(pool: Line[], vars: Record<string, string | number>): Line {
  return fill(pool[Math.floor(Math.random() * pool.length)], vars);
}
