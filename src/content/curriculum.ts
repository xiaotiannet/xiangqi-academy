import type { Color } from '../game/types';
import type { Lesson, Step, Unit, UnitColor } from './types';

const sq = (r: number, c: number): number => r * 9 + c;

/** 把 10 行 9 列的可视化局面转成数组 */
const L = (s: string): string[] =>
  s
    .trim()
    .split('\n')
    .map((l) => l.trim());

const palaceCells = (color: Color): number[] => {
  const out: number[] = [];
  const rows = color === 'r' ? [7, 8, 9] : [0, 1, 2];
  for (const r of rows) for (let c = 3; c <= 5; c++) out.push(sq(r, c));
  return out;
};

